def system_prompt(feature):
    return COMMON + '\n本次功能：' + FEATURES[feature][0] + '\n' + FEATURES[feature][2]


def encode(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':'))


def user_prompt(feature, settings, messages, previous, options):
    request={key:value for key,value in options.items() if key!='long_term_memory'}
    return encode({'feature': feature, 'timezone': 'Asia/Shanghai', 'group_settings': settings,
                   'request': request, 'long_term_memory': options.get('long_term_memory', []),
                   'previous_items': previous, 'messages': messages,
                   'instruction': '按指定功能分析这些材料。旧项只有存在明确联系和新证据时才更新。'})
